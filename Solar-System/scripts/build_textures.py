"""Build the pre-sized body textures that the app loads by default.

Bodies render with textures capped at MAX_TEXTURE_SIZE (1024 px). Shipping the
2048 px originals for that meant downloading about four times the pixels and then
shrinking each image on the main thread. This script writes a WebP copy of every
tracked body texture, scaled to fit 1024 px, under textures/1024/, and records each
original's size in src/rendering/textureSizes.js so close inspection knows when the
original is sharper than the copy.

Run from the repository root after adding or replacing a texture (and `git add` it):
    uv run --with pillow Solar-System/scripts/build_textures.py
"""

import hashlib
import json
import subprocess
from pathlib import Path

from PIL import Image

SOLAR = Path(__file__).resolve().parents[1]
TEXTURES = SOLAR / "textures"
VARIANT_DIR = "1024"
MAX_SIZE = 1024  # keep equal to MAX_TEXTURE_SIZE in src/core/config.js
QUALITY = 90
SIZES_MODULE = SOLAR / "src" / "rendering" / "textureSizes.js"
# The sky loads at full size and never through the 1024 copies.
SKIP = {"starmap_2020_4k.jpg"}
IMAGE_SUFFIXES = {".jpg", ".jpeg", ".png", ".webp"}


def tracked_textures() -> list[str]:
    # Only committed textures: local-only maps (see .gitignore) must not gain copies.
    output = subprocess.run(["git", "ls-files", "-z", "--", "."], cwd=TEXTURES, check=True,
                            capture_output=True, text=True).stdout
    return sorted(name for name in output.split("\0")
                  if name and Path(name).suffix.lower() in IMAGE_SUFFIXES
                  and not name.startswith(f"{VARIANT_DIR}/") and name not in SKIP)


def variant_path(name: str) -> Path:
    return TEXTURES / VARIANT_DIR / Path(name).with_suffix(".webp")


def build(name: str) -> tuple[int, int]:
    with Image.open(TEXTURES / name) as source:
        size = source.size
        has_alpha = source.mode in ("RGBA", "LA") or "transparency" in source.info
        image = source.convert("RGBA" if has_alpha else "RGB")
    scale = min(1.0, MAX_SIZE / max(size))
    if scale < 1:
        image = image.resize((max(1, round(size[0] * scale)), max(1, round(size[1] * scale))), Image.LANCZOS)
    target = variant_path(name)
    target.parent.mkdir(parents=True, exist_ok=True)
    # Alpha textures (ring profiles) are small and need exact edges, so keep them lossless.
    options = {"lossless": True} if has_alpha else {"quality": QUALITY}
    image.save(target, "WEBP", method=6, **options)
    return size


def source_hash(name: str) -> str:
    return hashlib.sha256((TEXTURES / name).read_bytes()).hexdigest()[:16]


def main() -> None:
    sizes, hashes = {}, {}
    for name in tracked_textures():
        sizes[name] = build(name)
        hashes[name] = source_hash(name)
        print(f"{name:45s} {sizes[name][0]}x{sizes[name][1]} -> {variant_path(name).stat().st_size / 1024:6.0f} KiB")
    size_entries = ",\n".join(f"  {json.dumps(name)}: [{w}, {h}]" for name, (w, h) in sizes.items())
    hash_entries = ",\n".join(f"  {json.dumps(name)}: {json.dumps(digest)}" for name, digest in hashes.items())
    SIZES_MODULE.write_text(
        "// Generated by scripts/build_textures.py; do not edit by hand.\n"
        "// Pixel size of each original body texture. The app loads the 1024 px copies in\n"
        f"// textures/{VARIANT_DIR}/ and fetches an original only when it is sharper.\n"
        f"export const ORIGINAL_TEXTURE_SIZES = {{\n{size_entries},\n}};\n\n"
        "// SHA-256 prefix of each original when its copy was built; scripts/smoke.mjs\n"
        "// compares it with the current file to catch a replaced texture with a stale copy.\n"
        f"export const SOURCE_TEXTURE_HASHES = {{\n{hash_entries},\n}};\n"
    )


if __name__ == "__main__":
    main()
